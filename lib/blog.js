export const getBlogPostPath = (slug) => `/blog/${slug}`;
export const getCmsBlogPostPath = (slug) => `${CMS_BLOG_POST_PATH}?slug=${encodeURIComponent(slug)}`;

const dateFormatter = new Intl.DateTimeFormat("en", {
  month: "short",
  day: "numeric",
  year: "numeric",
});

function toDate(value) {
  if (!value) {
    return null;
  }

  if (value instanceof Date) {
    return value;
  }

  if (typeof value.toDate === "function") {
    return value.toDate();
  }

  if (typeof value.seconds === "number") {
    return new Date(value.seconds * 1000);
  }

  const parsedDate = new Date(value);

  return Number.isNaN(parsedDate.getTime()) ? null : parsedDate;
}

function formatDate(value) {
  const date = toDate(value);

  return date ? dateFormatter.format(date) : "";
}

function toDateISO(value) {
  const date = toDate(value);

  return date ? date.toISOString().slice(0, 10) : "";
}

export function createSlug(value = "") {
  return value
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 90);
}

export function isRemoteUrl(value = "") {
  return /^https?:\/\//i.test(value) || value.startsWith("data:");
}

export function getPublicBlogPostPath(post) {
  if (!post) {
    return "/blog";
  }

  return post.source === "firestore" ? getCmsBlogPostPath(post.slug) : getBlogPostPath(post.slug);
}

export function estimateReadTime(text = "") {
  const words = text.trim().split(/\s+/).filter(Boolean).length;
  const minutes = Math.max(1, Math.ceil(words / 180));

  return `${minutes} min read`;
}

export function serializeSectionsToMarkdown(sections = []) {
  if (!Array.isArray(sections)) {
    return "";
  }

  return sections
    .map((section) => {
      const heading = section.heading ? `## ${section.heading}` : "";
      const paragraphs = Array.isArray(section.paragraphs) ? section.paragraphs : [];
      const list = Array.isArray(section.list) ? section.list.map((item) => `- ${item}`) : [];

      return [heading, ...paragraphs, ...list].filter(Boolean).join("\n\n");
    })
    .filter(Boolean)
    .join("\n\n");
}

export function parseBlogBody(markdown = "", fallbackBody = []) {
  if (!markdown.trim() && Array.isArray(fallbackBody) && fallbackBody.length) {
    return fallbackBody.map((section) => ({
      heading: section.heading || "Overview",
      paragraphs: Array.isArray(section.paragraphs) ? section.paragraphs : [],
      list: Array.isArray(section.list) ? section.list : undefined,
    }));
  }

  const blocks = markdown
    .split(/\n{2,}/g)
    .map((block) => block.trim())
    .filter(Boolean);

  if (!blocks.length) {
    return [
      {
        heading: "Overview",
        paragraphs: ["Article content is being prepared."],
      },
    ];
  }

  const sections = [];
  let currentSection = {
    heading: "Overview",
    paragraphs: [],
  };

  const commitSection = () => {
    if (currentSection.paragraphs.length || currentSection.list?.length || currentSection.heading !== "Overview") {
      sections.push(currentSection);
    }
  };

  blocks.forEach((block) => {
    if (block.startsWith("## ")) {
      commitSection();
      currentSection = {
        heading: block.replace(/^##\s+/, "").trim() || "Overview",
        paragraphs: [],
      };
      return;
    }

    if (block.startsWith("- ")) {
      const items = block
        .split(/\n/g)
        .map((line) => line.replace(/^-\s+/, "").trim())
        .filter(Boolean);

      currentSection.list = [...(currentSection.list || []), ...items];
      return;
    }

    currentSection.paragraphs.push(block.replace(/\n/g, " "));
  });

  commitSection();

  return sections.length ? sections : [currentSection];
}

export function normalizeStaticBlogPost(post) {
  return {
    ...post,
    source: "static",
    status: "published",
    image: post.image || DEFAULT_BLOG_IMAGE,
    coverImageUrl: post.image || DEFAULT_BLOG_IMAGE,
    bodyMarkdown: serializeSectionsToMarkdown(post.body),
  };
}

export function normalizeCmsBlogPost(data = {}, id = "") {
  const slug = data.slug || id || createSlug(data.title);
  const bodyMarkdown = data.bodyMarkdown || serializeSectionsToMarkdown(data.body);
  const publishedDate = data.publishedAt || data.updatedAt || data.createdAt;
  const date = data.date || formatDate(publishedDate);
  const dateISO = data.dateISO || toDateISO(publishedDate);
  const body = parseBlogBody(bodyMarkdown, data.body);
  const plainBody = body
    .flatMap((section) => [...(section.paragraphs || []), ...(section.list || [])])
    .join(" ");

  return {
    slug,
    source: "firestore",
    status: data.status || "draft",
    category: data.category || "Dental Care",
    date: date || "Recently updated",
    dateISO,
    readTime: data.readTime || estimateReadTime(`${data.title || ""} ${data.excerpt || ""} ${plainBody}`),
    title: data.title || "Untitled article",
    excerpt: data.excerpt || "",
    seoDescription: data.seoDescription || data.excerpt || "",
    image: data.coverImageUrl || data.image || DEFAULT_BLOG_IMAGE,
    imageAlt: data.imageAlt || data.title || "Dental article image",
    coverImageUrl: data.coverImageUrl || data.image || DEFAULT_BLOG_IMAGE,
    coverImagePath: data.coverImagePath || "",
    body,
    bodyMarkdown,
    createdAt: data.createdAt || null,
    updatedAt: data.updatedAt || null,
    publishedAt: data.publishedAt || null,
  };
}

export function getBlogPost(slug) {
  return BLOG_POSTS.find((post) => post.slug === slug);
}

export function getRelatedPosts(slug, limit = 2) {
  return BLOG_POSTS.filter((post) => post.slug !== slug).slice(0, limit);
}
